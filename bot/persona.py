_corpus_cache: list[dict] | None = None


def _load_corpus() -> list[dict]:
    global _corpus_cache
    if _corpus_cache is None:
        if not CORPUS_PATH.exists():
            _corpus_cache = []
        else:
            _corpus_cache = json.loads(CORPUS_PATH.read_text(encoding="utf-8"))
    return _corpus_cache


def _short_messages(max_len: int = 220) -> list[str]:
    return [m["text"] for m in _load_corpus() if 3 <= len(m["text"]) <= max_len]


def _long_messages(min_len: int = 250, max_len: int = 900) -> list[str]:
    return [m["text"] for m in _load_corpus() if min_len <= len(m["text"]) <= max_len]


def sample_dialogue_examples(
    seed: int | None = None, *, n: int = 12
) -> list[dict[str, str]]:
    """Возвращает случайные диалоговые пары как сообщения для chat-completions.

    Формат входящих юзерских реплик в проде — `[<имя>]: <текст>`,
    поэтому и в примерах оборачиваем вопрос в `[анон]: ...`, чтобы
    модель опознала это как тот же паттерн.
    """
    rng = random.Random(seed)
    pairs = list(DIALOGUE_EXAMPLES)
    rng.shuffle(pairs)
    picked = pairs[: min(n, len(pairs))]

    messages: list[dict[str, str]] = []
    for question, answer in picked:
        messages.append({"role": "user", "content": f"[анон]: {question}"})
        messages.append({"role": "assistant", "content": answer})
    return messages


def sample_style_examples(seed: int | None = None, *, short_n: int = 10, long_n: int = 2) -> str:
    """Подбирает примеры стиля для подмешивания в системный промпт."""
    rng = random.Random(seed)
    shorts = _short_messages()
    longs = _long_messages()

    rng.shuffle(shorts)
    rng.shuffle(longs)

    picked_short = shorts[:short_n]
    picked_long = longs[:long_n]

    blocks: list[str] = []
    if picked_short:
        blocks.append("ПРИМЕРЫ КОРОТКИХ РЕПЛИК (твой стиль):")
        blocks.extend(f"- {t}" for t in picked_short)

    if picked_long:
        blocks.append("")
        blocks.append("ПРИМЕРЫ ДЛИННЫХ ПОСТОВ (твой стиль для развёрнутых ответов):")
        for t in picked_long:
            blocks.append("---")
            blocks.append(t)

    return "\n".join(blocks)


def build_system_prompt(seed: int | None = None) -> str:
    examples = sample_style_examples(seed=seed)
    if not examples:
        return PERSONA_SYSTEM_PROMPT
    return f"{PERSONA_SYSTEM_PROMPT}\n\n{examples}"
