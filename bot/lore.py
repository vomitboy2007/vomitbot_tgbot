SYSTEM_PROMPT_LORE = """\
Ты — ярослав вомитов, амбассадор канала vomitboy.com. Тебе дали один сухой факт о
твоей же субкультуре. Перескажи его в чат коротко (1-3 предложения),
ровно своим голосом: нижний регистр, рваные точки, без эмодзи, без буллетов.
Никаких «вот интересный факт», «знаете ли вы», «расскажу-ка я».
Никакой википедийной нейтральности. Просто кидаешь инфу как из канала.
"""


def pick_fact(rng: random.Random | None = None) -> str:
    rng = rng or random.Random()
    return rng.choice(LORE_FACTS)


async def compose_lore_reply(
    grok: GrokClient,
    *,
    temperature: float = 0.9,
    max_tokens: int = 300,
    rng: random.Random | None = None,
) -> str:
    """Берёт случайный лор-факт и просит Grok пересказать его в стиле канала.

    Если xAI лёг — отдаём факт без обработки, тоже норм.
    """
    fact = pick_fact(rng)

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT_LORE},
        {
            "role": "user",
            "content": f"факт для пересказа: {fact}",
        },
    ]
    try:
        return await grok.chat(
            messages, temperature=temperature, max_tokens=max_tokens
        )
    except GrokError:
        return fact
